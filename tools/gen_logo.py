#!/usr/bin/env python3
# Generates src/pico/ui/UiLogo.c, Help > About's logo, from img/logo.jpg: 128 x 128
# framebuffer pixels in the Amiga's 0x0RGB (the menu draws straight into DIRECT
# rows), a 4x4 Bayer dither over the 4-bit channels.
#   tools/gen_logo.py [img/logo.jpg] [src/pico/ui/UiLogo.c]
import sys
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else "img/logo.jpg"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/pico/ui/UiLogo.c"
N = 128
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]

im = Image.open(SRC).convert("RGB").resize((N, N), Image.LANCZOS)
px = im.load()
words = []
for y in range(N):
    for x in range(N):
        t = (BAYER[y & 3][x & 3] + 0.5) / 16.0
        c = 0
        for v in px[x, y]:
            q = min(15, int(v * 15 / 255.0 + t))
            c = (c << 4) | q
        words.append(c)

with open(DST, "w") as f:
    f.write("// pico-amiga - Help > About's logo (UiLogo.h), generated by tools/gen_logo.py\n"
            "// from img/logo.jpg: do not edit.\n"
            '#include "UiLogo.h"\n\n'
            "const uint16_t ui_logo128[UI_LOGO_W * UI_LOGO_H] = {\n")
    for i in range(0, len(words), 16):
        f.write("    " + ", ".join("0x%03X" % w for w in words[i:i + 16]) + ",\n")
    f.write("};\n")
