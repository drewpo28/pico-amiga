// USB HID keyboard usage -> Amiga raw keycode (see K() below).
//
// PC keys without an Amiga twin: Insert/F11 -> Help, Home/End -> keypad ( ),
// PgUp/PgDn -> right/left Amiga, Win keys -> left/right Amiga.  The "Amiga"
// modifiers are where an A500 has them only via the Win keys; PgUp/PgDn give
// keyboards without Win keys a way to type Amiga-shortcuts.
#pragma once
#include <stdint.h>

#define AK_NONE   0xFF   // in K(): mapped to nothing (handled by the caller)
#define AK_LSHIFT 0x60
#define AK_RSHIFT 0x61
#define AK_CTRL   0x63
#define AK_LALT   0x64
#define AK_RALT   0x65
#define AK_LAMIGA 0x66
#define AK_RAMIGA 0x67

// Entries are K(code): bit 8 marks a mapped key, so unlisted usages (0) are
// distinguishable from Amiga keycode $00 (the ` key).
#define K(c) (uint16_t)(0x100 | (c))
static const uint16_t hid_to_amiga[256] = {
    [0x04] = K(0x20), [0x05] = K(0x35), [0x06] = K(0x33), [0x07] = K(0x22),   // A B C D
    [0x08] = K(0x12), [0x09] = K(0x23), [0x0A] = K(0x24), [0x0B] = K(0x25),   // E F G H
    [0x0C] = K(0x17), [0x0D] = K(0x26), [0x0E] = K(0x27), [0x0F] = K(0x28),   // I J K L
    [0x10] = K(0x37), [0x11] = K(0x36), [0x12] = K(0x18), [0x13] = K(0x19),   // M N O P
    [0x14] = K(0x10), [0x15] = K(0x13), [0x16] = K(0x21), [0x17] = K(0x14),   // Q R S T
    [0x18] = K(0x16), [0x19] = K(0x34), [0x1A] = K(0x11), [0x1B] = K(0x32),   // U V W X
    [0x1C] = K(0x15), [0x1D] = K(0x31),                                 // Y Z
    [0x1E] = K(0x01), [0x1F] = K(0x02), [0x20] = K(0x03), [0x21] = K(0x04),   // 1 2 3 4
    [0x22] = K(0x05), [0x23] = K(0x06), [0x24] = K(0x07), [0x25] = K(0x08),   // 5 6 7 8
    [0x26] = K(0x09), [0x27] = K(0x0A),                                 // 9 0
    [0x28] = K(0x44), [0x29] = K(0x45), [0x2A] = K(0x41), [0x2B] = K(0x42),   // Return Esc Backspace Tab
    [0x2C] = K(0x40), [0x2D] = K(0x0B), [0x2E] = K(0x0C), [0x2F] = K(0x1A),   // Space - = [
    [0x30] = K(0x1B), [0x31] = K(0x0D), [0x32] = K(0x2B), [0x33] = K(0x29),   // ] \ #(intl) ;
    [0x34] = K(0x2A), [0x35] = K(0x00), [0x36] = K(0x38), [0x37] = K(0x39),   // ' ` , .
    [0x38] = K(0x3A), [0x39] = K(0x62),                                 // / CapsLock
    [0x3A] = K(0x50), [0x3B] = K(0x51), [0x3C] = K(0x52), [0x3D] = K(0x53),   // F1-F4
    [0x3E] = K(0x54), [0x3F] = K(0x55), [0x40] = K(0x56), [0x41] = K(0x57),   // F5-F8
    [0x42] = K(0x58), [0x43] = K(0x59), [0x44] = K(0x5F),                  // F9 F10 F11=Help
    [0x45] = K(AK_NONE),                                             // F12: emulator reset
    [0x49] = K(0x5F), [0x4A] = K(0x5A), [0x4B] = K(AK_RAMIGA),             // Insert=Help Home=KP( PgUp=RAmiga
    [0x4C] = K(0x46), [0x4D] = K(0x5B), [0x4E] = K(AK_LAMIGA),             // Delete End=KP) PgDn=LAmiga
    [0x4F] = K(0x4E), [0x50] = K(0x4F), [0x51] = K(0x4D), [0x52] = K(0x4C),   // Right Left Down Up
    [0x54] = K(0x5C), [0x55] = K(0x5D), [0x56] = K(0x4A), [0x57] = K(0x5E),   // KP / * - +
    [0x58] = K(0x43),                                                // KP Enter
    [0x59] = K(0x1D), [0x5A] = K(0x1E), [0x5B] = K(0x1F), [0x5C] = K(0x2D),   // KP 1 2 3 4
    [0x5D] = K(0x2E), [0x5E] = K(0x2F), [0x5F] = K(0x3D), [0x60] = K(0x3E),   // KP 5 6 7 8
    [0x61] = K(0x3F), [0x62] = K(0x0F), [0x63] = K(0x3C),                  // KP 9 0 .
    [0x64] = K(0x30),                                                // <> (intl, left of Z)
};

// HID modifier byte bit -> Amiga key (LCtrl LShift LAlt LGUI RCtrl RShift RAlt RGUI).
static const uint8_t hid_mod_to_amiga[8] = {
    AK_CTRL, AK_LSHIFT, AK_LALT, AK_LAMIGA, AK_CTRL, AK_RSHIFT, AK_RALT, AK_RAMIGA,
};
